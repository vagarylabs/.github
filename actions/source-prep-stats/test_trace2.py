class CompletenessTests(unittest.TestCase):
    BASE = {"shallow": False, "partial": False, "sparse": False, "files_skipped": 0, "has_submodules": False}

    def test_complete_only_when_nothing_is_truncated(self):
        self.assertEqual(srcstats.completeness("success", self.BASE, {}), ("complete", []))

    def test_truncations(self):
        cases = {
            "shallow": {"shallow": True}, "partial": {"partial": True}, "sparse": {"sparse": True},
            "skip-worktree without sparse config": {"files_skipped": 3},
            "submodules not fetched": {"has_submodules": True},
        }
        for name, change in cases.items():
            with self.subTest(name):
                state, reasons = srcstats.completeness("success", dict(self.BASE, **change), {"submodules": "false"})
                self.assertEqual(state, "incomplete")
                self.assertEqual(len(reasons), 1)

    def test_submodules_fetched_is_not_a_truncation(self):
        shape = dict(self.BASE, has_submodules=True)
        self.assertEqual(srcstats.completeness("success", shape, {"submodules": "recursive"})[0], "complete")

    def test_unknown_facts_never_round_up_to_complete(self):
        for key in ("shallow", "partial", "sparse", "files_skipped", "has_submodules"):
            with self.subTest(key):
                self.assertEqual(srcstats.completeness("success", dict(self.BASE, **{key: None}), {})[0], "unknown")

    def test_unknown_submodules_do_not_matter_once_submodules_were_fetched(self):
        shape = dict(self.BASE, has_submodules=None)
        self.assertEqual(srcstats.completeness("success", shape, {"submodules": "recursive"}), ("complete", []))

    def test_failed_checkout_is_incomplete(self):
        self.assertEqual(srcstats.completeness("failure", self.BASE, {}), ("incomplete", ["checkout-failure"]))

    def test_no_repository_is_unknown(self):
        self.assertEqual(srcstats.completeness("success", None, {}), ("unknown", []))


class SchemaValidatorTests(unittest.TestCase):
    """The stdlib validator must actually reject things, or every schema assertion above is vacuous."""

    def test_rejections(self):
        schema = {"type": "object", "additionalProperties": False, "required": ["a"],
                  "properties": {"a": {"type": ["integer", "null"], "minimum": 0},
                                 "b": {"anyOf": [{"type": "integer"}, {"const": "full"}]},
                                 "c": {"type": "string", "pattern": "^[0-9a-f]{4}$"}}}
        self.assertEqual(srcstats.validate({"a": 1, "b": "full", "c": "00ff"}, schema), [])
        for bad in ({}, {"a": -1}, {"a": True}, {"a": 1.5}, {"a": 1, "z": 0}, {"a": 1, "b": "deep"},
                    {"a": 1, "c": "xyz"}):
            with self.subTest(bad=bad):
                self.assertNotEqual(srcstats.validate(bad, schema), [])

    def test_non_finite_numbers_are_not_numbers(self):
        """nan < 0 is False, so a minimum alone lets NaN through; JSON has no NaN or Infinity at all."""
        schema = {"type": ["number", "null"], "minimum": 0}
        for bad in (float("nan"), float("inf"), float("-inf")):
            with self.subTest(bad=bad):
                self.assertNotEqual(srcstats.validate(bad, schema), [])
                with self.assertRaises(ValueError):
                    srcstats.dumps({"fetch_seconds": bad})
        self.assertEqual(srcstats.validate(0.5, schema), [], "positive control")

    def test_schema_files_are_valid_json_with_versioned_ids(self):
        for name, version in (("source-prep.v1.json", "source-prep.v1"), ("job-telemetry.v1.json", "job-telemetry.v1")):
            with open(os.path.join(HERE, "schema", name)) as fh:
                doc = json.load(fh)
            self.assertEqual(doc["properties"]["schema"], {"const": version})
            self.assertTrue(doc["$id"].endswith(name))


