def proc(sid, name, hierarchy, argv, code=0, t=0.5, at="2026-10-15T00:00:00.000000Z", errors=(), data=(),
         exited=True, exe="2.50.1"):
    events = [{"event": "version", "sid": sid, "evt": "4", "exe": exe},
              {"event": "start", "sid": sid, "argv": ["git"] + argv, "time": at, "t_abs": 0.0},
              {"event": "cmd_name", "sid": sid, "name": name, "hierarchy": hierarchy}]
    events += [{"event": "error", "sid": sid, "msg": m, "fmt": "%s"} for m in errors]
    events += [{"event": "data", "sid": sid, "category": c, "key": k, "value": v, "nesting": 3} for c, k, v in data]
    if exited:
        events.append({"event": "exit", "sid": sid, "code": code, "t_abs": t})
    return events


class Trace:
    def __init__(self):
        self.dir = tempfile.mkdtemp(prefix="trace2-")
        self.n = 0

    def add(self, events, raw_tail=""):
        self.n += 1
        with open(os.path.join(self.dir, "%04d" % self.n), "w") as fh:
            fh.write("".join(json.dumps(e) + "\n" for e in events) + raw_tail)

    def summary(self):
        s, reason = srcstats.summarize_trace(self.dir)
        self.assert_no_raw(s)
        return s, reason

    @staticmethod
    def assert_no_raw(s):
        text = json.dumps(s)
        for leak in ("127.0.0.1", "http://", "https://", "argv", "unable to access", "/fixture"):
            assert leak not in text, "raw trace content leaked into the summary: %s" % leak

    def close(self):
        shutil.rmtree(self.dir, ignore_errors=True)


