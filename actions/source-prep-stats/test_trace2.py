"""summarize_trace: allow-listed aggregates from a GIT_TRACE2_EVENT directory.

Real traces (fixtures/trace2, regenerated by fixtures/make_trace2_fixtures.py) pin the reading of what git
actually writes; small synthetic traces in the same event shapes pin the edge rules.
"""
import json
import os
import shutil
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import srcstats  # noqa: E402

FIXTURES = os.path.join(HERE, "fixtures", "trace2")
ROOT = "20261015T000000.000000Z-H00000000-P"


def proc(sid, name, hierarchy, argv, code=0, t=0.5, at="2026-10-15T00:00:00.000000Z", errors=(), data=(),
         exited=True):
    events = [{"event": "version", "sid": sid, "evt": "4", "exe": "2.50.1"},
              {"event": "start", "sid": sid, "argv": ["git"] + argv, "time": at, "t_abs": 0.0},
              {"event": "cmd_name", "sid": sid, "name": name, "hierarchy": hierarchy}]
    events += [{"event": "error", "sid": sid, "msg": m, "fmt": "%s"} for m in errors]
    events += [{"event": "data", "sid": sid, "category": c, "key": k, "value": v, "nesting": 3} for c, k, v in data]
    if exited:
        events.append({"event": "exit", "sid": sid, "code": code, "t_abs": t})
    return events


class Trace:
    def __init__(self):
        self.dir = tempfile.mkdtemp(prefix="trace2-")
        self.n = 0

    def add(self, events, raw_tail=""):
        self.n += 1
        with open(os.path.join(self.dir, "%04d" % self.n), "w") as fh:
            fh.write("".join(json.dumps(e) + "\n" for e in events) + raw_tail)

    def summary(self):
        s, reason = srcstats.summarize_trace(self.dir)
        self.assert_no_raw(s)
        return s, reason

    @staticmethod
    def assert_no_raw(s):
        text = json.dumps(s)
        for leak in ("127.0.0.1", "http", "argv", "unable to access", "/fixture"):
            assert leak not in text, "raw trace content leaked into the summary: %s" % leak

    def close(self):
        shutil.rmtree(self.dir, ignore_errors=True)


FETCH = ["-c", "protocol.version=2", "fetch", "--no-tags", "origin", "+refs/heads/main:refs/remotes/origin/main"]
LAZY = ["-c", "fetch.negotiationAlgorithm=noop", "fetch", "origin", "--no-tags", "--no-write-fetch-head",
        "--recurse-submodules=no", "--filter=blob:none", "--stdin"]


class RealFixtureTests(unittest.TestCase):
    def test_http_429_then_identical_retry(self):
        s, _ = srcstats.summarize_trace(os.path.join(FIXTURES, "http-429-retry"))
        Trace.assert_no_raw(s)
        self.assertEqual((s["fetch_attempts"], s["failed_fetch_attempts"], s["retries"], s["throttle_hits"]),
                         (2, 1, 1, 1))
        self.assertEqual(s["objects_received"], 48)
        self.assertEqual(s["protocol_version"], "2")
        self.assertEqual((s["lazy_fetches"], s["lazy_objects"]), (0, 0))
        self.assertEqual(s["trace"]["unterminated"], 0)

    def test_file_transport_blobless_checkout(self):
        s, _ = srcstats.summarize_trace(os.path.join(FIXTURES, "file-blobless-checkout"))
        Trace.assert_no_raw(s)
        self.assertEqual(s["trace"]["excluded_server_processes"], 4, "upload-pack + pack-objects, twice")
        self.assertEqual((s["fetch_attempts"], s["retries"], s["throttle_hits"]), (1, 0, 0))
        self.assertEqual(s["filter_effective"], "blob:none")
        self.assertEqual((s["lazy_fetches"], s["lazy_fetch_failures"], s["lazy_objects"]), (1, 0, 12))
        self.assertEqual(s["objects_received"], 48, "36 commits+trees, then 12 blobs by lazy fetch")


class SyntheticTests(unittest.TestCase):
    def setUp(self):
        self.t = Trace()

    def tearDown(self):
        self.t.close()

    def test_missing_or_empty_trace_is_unknown_not_zero(self):
        self.assertEqual(srcstats.summarize_trace(None)[0], None)
        self.assertEqual(srcstats.summarize_trace(os.path.join(self.t.dir, "absent"))[0], None)
        s, reason = srcstats.summarize_trace(self.t.dir)
        self.assertIsNone(s)
        self.assertIn("no git process", reason)

    def test_one_throttled_attempt_is_one_hit_however_many_processes_report_it(self):
        a = ROOT + "1"
        self.t.add(proc(a, "fetch", "fetch", FETCH, code=128, errors=["could not fetch: rate limit exceeded"]))
        self.t.add(proc(a + "/x", "remote-curl", "fetch/_run_dashed_/remote-curl", ["remote-https", "origin", "u"],
                        code=128, errors=["unable to access 'https://h/r/': The requested URL returned error: 429"]))
        s, _ = self.t.summary()
        self.assertEqual((s["throttle_hits"], s["retries"], s["failed_fetch_attempts"]), (1, 0, 1))

    def test_secondary_rate_limit_and_too_many_requests_count(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH, code=128, at="2026-10-15T00:00:01Z",
                        errors=["You have exceeded a secondary rate limit"]))
        self.t.add(proc(ROOT + "2", "fetch", "fetch", FETCH, code=128, at="2026-10-15T00:00:02Z",
                        errors=["RPC failed; HTTP 429 Too Many Requests"]))
        self.t.add(proc(ROOT + "3", "fetch", "fetch", FETCH, code=0, at="2026-10-15T00:00:03Z"))
        s, _ = self.t.summary()
        self.assertEqual((s["fetch_attempts"], s["failed_fetch_attempts"], s["retries"], s["throttle_hits"]),
                         (3, 2, 2, 2))
        self.assertEqual(s["fetch_seconds"], 1.5)

    def test_other_errors_are_not_throttling(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH, code=128, errors=["repository not found (port 4290)"]))
        s, _ = self.t.summary()
        self.assertEqual(s["throttle_hits"], 0)

    def test_server_side_processes_are_excluded(self):
        a = ROOT + "1"
        self.t.add(proc(a, "fetch", "fetch", FETCH))
        self.t.add(proc(a + "/u", "upload-pack", "fetch/upload-pack", ["upload-pack", "/srv"],
                        errors=["429 shaped server text"], data=[("transfer", "negotiated-version", "1")]))
        self.t.add(proc(a + "/u/p", "pack-objects", "fetch/upload-pack/pack-objects",
                        ["pack-objects", "--pack_header=2,999"]))
        s, _ = self.t.summary()
        self.assertEqual(s["trace"]["excluded_server_processes"], 2)
        self.assertEqual((s["throttle_hits"], s["objects_received"], s["protocol_version"]), (0, 0, None))

    def test_a_retry_must_repeat_the_same_command(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH, code=128, at="2026-10-15T00:00:01Z"))
        self.t.add(proc(ROOT + "2", "fetch", "fetch", FETCH[:-1] + ["+refs/tags/*:refs/tags/*"],
                        at="2026-10-15T00:00:02Z"))
        s, _ = self.t.summary()
        self.assertEqual((s["fetch_attempts"], s["failed_fetch_attempts"], s["retries"]), (2, 1, 0))

    def test_lazy_and_nested_fetches_are_not_attempts(self):
        a, c = ROOT + "1", ROOT + "2"
        self.t.add(proc(a, "fetch", "fetch", FETCH))
        self.t.add(proc(a + "/s", "fetch", "fetch/fetch", ["fetch", "--recurse-submodules"]))  # submodule fetch
        self.t.add(proc(c, "checkout", "checkout", ["checkout", "-B", "main"], data=[("promisor", "fetch_count", "7")]))
        self.t.add(proc(c + "/l", "fetch", "checkout/fetch", LAZY, code=1))
        self.t.add(proc(c + "/l/i", "index-pack", "checkout/fetch/index-pack", ["index-pack", "--pack_header=2,7"]))
        s, _ = self.t.summary()
        self.assertEqual((s["fetch_attempts"], s["lazy_fetches"], s["lazy_fetch_failures"], s["lazy_objects"]),
                         (1, 1, 1, 7))
        self.assertEqual(s["objects_received"], 7)

    def test_lazy_fetch_without_a_count_is_unknown(self):
        self.t.add(proc(ROOT + "1", "checkout", "checkout", ["checkout"]))
        self.t.add(proc(ROOT + "1/l", "fetch", "checkout/fetch", LAZY))
        s, _ = self.t.summary()
        self.assertEqual(s["lazy_fetches"], 1)
        self.assertIsNone(s["lazy_objects"], "older git emits no promisor/fetch_count: unknown, not 0")

    def test_negotiation_sums_rounds_and_haves(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH, data=[
            ("negotiation_v2", "haves_added", "16"), ("negotiation_v2", "haves_added", "4"),
            ("negotiation_v2", "total_rounds", "2"), ("fetch", "filter/effective", "tree:0"),
            ("transfer", "negotiated-version", "2")]))
        s, _ = self.t.summary()
        self.assertEqual((s["negotiation_rounds"], s["haves_sent"], s["filter_effective"], s["protocol_version"]),
                         (2, 20, "tree:0", "2"))

    def test_fetch_without_negotiation_data_is_unknown(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH))
        s, _ = self.t.summary()
        self.assertEqual((s["negotiation_rounds"], s["haves_sent"]), (None, None))

    def test_no_fetch_at_all_is_measured_zero(self):
        self.t.add(proc(ROOT + "1", "rev-parse", "rev-parse", ["rev-parse", "HEAD"]))
        s, _ = self.t.summary()
        self.assertEqual((s["fetch_attempts"], s["fetch_seconds"], s["negotiation_rounds"], s["lazy_objects"]),
                         (0, 0, 0, 0))

    def test_unterminated_process_and_bad_lines_mark_the_trace(self):
        self.t.add(proc(ROOT + "1", "fetch", "fetch", FETCH, exited=False), raw_tail='{"event": "data", "si')
        self.t.add([{"event": "start"}])
        s, _ = self.t.summary()
        self.assertEqual((s["trace"]["unterminated"], s["trace"]["bad_lines"]), (1, 2))
        self.assertEqual(s["failed_fetch_attempts"], 1, "an attempt that never exited did not succeed")
        self.assertIsNone(s["fetch_seconds"], "its duration was not measured")

    def test_signal_ends_a_process_without_a_code(self):
        events = proc(ROOT + "1", "fetch", "fetch", FETCH, exited=False)
        events.append({"event": "signal", "sid": ROOT + "1", "signo": 15, "t_abs": 2.0})
        self.t.add(events)
        s, _ = self.t.summary()
        self.assertEqual((s["trace"]["unterminated"], s["failed_fetch_attempts"]), (0, 1))

    def test_detached_child_repeating_exit_keeps_the_first(self):
        events = proc(ROOT + "1", "fetch", "fetch", FETCH, code=0, t=1.0)
        events.append({"event": "exit", "sid": ROOT + "1", "code": 3, "t_abs": 9.0})
        self.t.add(events)
        s, _ = self.t.summary()
        self.assertEqual((s["failed_fetch_attempts"], s["fetch_seconds"]), (0, 1.0))


class CompletenessTests(unittest.TestCase):
    BASE = {"shallow": False, "partial": False, "sparse": False, "files_skipped": 0, "has_submodules": False}

    def test_complete_only_when_nothing_is_truncated(self):
        self.assertEqual(srcstats.completeness("success", self.BASE, {}), ("complete", []))

    def test_truncations(self):
        cases = {
            "shallow": {"shallow": True}, "partial": {"partial": True}, "sparse": {"sparse": True},
            "skip-worktree without sparse config": {"files_skipped": 3},
            "submodules not fetched": {"has_submodules": True},
        }
        for name, change in cases.items():
            with self.subTest(name):
                state, reasons = srcstats.completeness("success", dict(self.BASE, **change), {"submodules": "false"})
                self.assertEqual(state, "incomplete")
                self.assertEqual(len(reasons), 1)

    def test_submodules_fetched_is_not_a_truncation(self):
        shape = dict(self.BASE, has_submodules=True)
        self.assertEqual(srcstats.completeness("success", shape, {"submodules": "recursive"})[0], "complete")

    def test_unknown_facts_never_round_up_to_complete(self):
        for key in ("shallow", "partial", "sparse", "files_skipped"):
            with self.subTest(key):
                self.assertEqual(srcstats.completeness("success", dict(self.BASE, **{key: None}), {})[0], "unknown")

    def test_failed_checkout_is_incomplete(self):
        self.assertEqual(srcstats.completeness("failure", self.BASE, {}), ("incomplete", ["checkout-failure"]))

    def test_no_repository_is_unknown(self):
        self.assertEqual(srcstats.completeness("success", None, {}), ("unknown", []))


class SchemaValidatorTests(unittest.TestCase):
    """The stdlib validator must actually reject things, or every schema assertion above is vacuous."""

    def test_rejections(self):
        schema = {"type": "object", "additionalProperties": False, "required": ["a"],
                  "properties": {"a": {"type": ["integer", "null"], "minimum": 0},
                                 "b": {"anyOf": [{"type": "integer"}, {"const": "full"}]},
                                 "c": {"type": "string", "pattern": "^[0-9a-f]{4}$"}}}
        self.assertEqual(srcstats.validate({"a": 1, "b": "full", "c": "00ff"}, schema), [])
        for bad in ({}, {"a": -1}, {"a": True}, {"a": 1.5}, {"a": 1, "z": 0}, {"a": 1, "b": "deep"},
                    {"a": 1, "c": "xyz"}):
            with self.subTest(bad=bad):
                self.assertNotEqual(srcstats.validate(bad, schema), [])

    def test_schema_files_are_valid_json_with_versioned_ids(self):
        for name, version in (("source-prep.v1.json", "source-prep.v1"), ("job-telemetry.v1.json", "job-telemetry.v1")):
            with open(os.path.join(HERE, "schema", name)) as fh:
                doc = json.load(fh)
            self.assertEqual(doc["properties"]["schema"], {"const": version})
            self.assertTrue(doc["$id"].endswith(name))


